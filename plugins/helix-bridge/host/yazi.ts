// The file tree beside the editor is yazi, in its own bb terminal session.
// This prepares its configuration directory in the plugin's data: the user's
// own yazi configuration is linked in (keymap, theme, init.lua, plugins,
// flavors) and never written; yazi.toml is a copy of theirs with two settings
// added only when they have not set them: one column (the pane is narrow) and
// an `edit` opener that opens the file in the bound Helix and returns at once.
// The opener is a small shell script (OPENER_SCRIPT) that talks to Helix's
// bridge socket directly, so opening a file costs a few milliseconds instead
// of starting the bb CLI; `bb hx tree-open` is its fallback.
import { execFile } from "node:child_process";
import { chmodSync, existsSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { resolveExecutable } from "./doctor";

/** Opens the chosen files in the Helix serving this tree's thread (the script below). */
export const OPEN_COMMAND = `"$HELIX_BRIDGE_OPEN" "$@"`;

/**
 * Open the files yazi passes in the Helix bound to this tree's thread: find
 * its registry file by BB_THREAD_ID in the bridge directory, and send one
 * `editor/open` per file over its socket (the first focused). Falls back to
 * `bb hx tree-open` when there is no such Helix, no `nc -U` or `python3`, or
 * Helix does not answer with a result.
 */
export const OPENER_SCRIPT = String.raw`#!/bin/sh
# Generated by Helix Bridge: open files chosen in the file tree in Helix.
dir=$HELIX_BRIDGE_DIR
[ -n "$dir" ] || dir=$XDG_CACHE_HOME
[ -n "$dir" ] && [ -z "$HELIX_BRIDGE_DIR" ] && dir="$dir/helix/bridge"
[ -n "$dir" ] || dir="$HOME/.cache/helix/bridge"
bb=$BB_CLI
[ -n "$bb" ] || bb=bb
fallback() { exec "$bb" hx tree-open "$@"; }
[ $# -gt 0 ] || exit 0
case "$BB_THREAD_ID" in ''|*[!A-Za-z0-9_-]*) fallback "$@" ;; esac
regs=$(grep -l -E "\"BB_THREAD_ID\"[[:space:]]*:[[:space:]]*\"$BB_THREAD_ID\"" "$dir"/*.json 2>/dev/null)
[ -n "$regs" ] || fallback "$@"
reg=$(ls -t $regs 2>/dev/null | head -n 1)
sock=$(sed -n 's/.*"socket"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$reg" | head -n 1)
[ -S "$sock" ] || fallback "$@"
esc() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }
msg=""
i=0
for f in "$@"; do
  i=$((i + 1))
  focus=false
  [ "$i" -eq 1 ] && focus=true
  msg="$msg{\"jsonrpc\":\"2.0\",\"id\":$i,\"method\":\"editor/open\",\"params\":{\"path\":\"$(esc "$f")\",\"focus\":$focus,\"interrupt\":\"always\"}}
"
done
if command -v nc >/dev/null 2>&1; then
  # nc quits as soon as its input ends, before Helix answers: hold the input
  # open a moment (this script runs detached; the file opens at once anyway).
  out=$({ printf '%s' "$msg"; sleep 1; } | nc -U -w 2 "$sock" 2>/dev/null)
elif command -v python3 >/dev/null 2>&1; then
  out=$(printf '%s' "$msg" | python3 -c 'import socket,sys
s=socket.socket(socket.AF_UNIX); s.settimeout(2); s.connect(sys.argv[1]); s.sendall(sys.stdin.buffer.read())
print(s.recv(65536).decode(errors="replace"))' "$sock" 2>/dev/null)
else
  fallback "$@"
fi
case "$out" in *'"result"'*) exit 0 ;; esac
fallback "$@"
`;

const LINKED = ["keymap.toml", "theme.toml", "init.lua", "package.toml", "plugins", "flavors"];

export interface YaziSetup {
  yazi: string | null;
  ya: string | null;
  version: string | null;
  configDir: string | null;
  /** The opener script (OPENER_SCRIPT) in configDir. */
  opener?: string | null;
  /** Where the user's own configuration was read from, if anywhere. */
  userConfig: string | null;
}

export function userConfigDir(env: NodeJS.ProcessEnv = process.env): string {
  return env.YAZI_CONFIG_HOME || join(env.XDG_CONFIG_HOME || join(homedir(), ".config"), "yazi");
}

/**
 * The tree's yazi.toml: the user's text with `ratio` and the `edit` opener
 * added when absent. Keys go right under an existing table header, or in a
 * new table at the end, so the result stays valid TOML.
 */
export function treeYaziToml(user: string | null): string {
  let text = user ?? "";
  const add = (table: string, key: string, line: string) => {
    const header = new RegExp(`^\\s*\\[${table}\\]\\s*$`, "mu");
    const section = (() => {
      const start = header.exec(text);
      if (!start) return null;
      const rest = text.slice(start.index + start[0].length);
      const next = /^\s*\[/mu.exec(rest);
      return rest.slice(0, next ? next.index : rest.length);
    })();
    if (section !== null && new RegExp(`^\\s*${key}\\s*=`, "mu").test(section)) return;
    const match = header.exec(text);
    if (match) text = `${text.slice(0, match.index + match[0].length)}\n${line}${text.slice(match.index + match[0].length)}`;
    else text = `${text.trimEnd()}${text.trim() ? "\n\n" : ""}[${table}]\n${line}\n`;
  };
  // yazi 0.4 calls the file browser `manager`.
  add("manager", "ratio", "ratio = [0, 1, 0]");
  add("opener", "edit", `edit = [{ run = '${OPEN_COMMAND}', desc = "Open in Helix", orphan = true, for = "unix" }]`);
  return `# Generated by Helix Bridge for the file tree beside the editor, from your\n# own yazi.toml (which is never written).\n${text}`;
}

/**
 * Escape closes the tree (yazi quits; the pane hides and Helix gets focus),
 * added only when the user has no keymap of their own. Escape in yazi's
 * prompts still cancels the prompt: this binds the file list only.
 */
export const TREE_KEYMAP = `# Generated by Helix Bridge for the file tree beside the editor.
[manager]
prepend_keymap = [{ on = "<Esc>", run = "quit", desc = "Close the file tree" }]
`;

export function prepareYazi(dataDir: string): YaziSetup {
  const yazi = resolveExecutable("yazi");
  const ya = resolveExecutable("ya");
  if (!yazi) return { yazi: null, ya, version: null, configDir: null, userConfig: null };
  const user = userConfigDir();
  const hasUser = existsSync(user);
  const dir = join(dataDir, "yazi-config");
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  if (hasUser) {
    for (const name of LINKED) {
      const from = join(user, name);
      if (existsSync(from)) symlinkSync(from, join(dir, name));
    }
  }
  const userToml = hasUser && existsSync(join(user, "yazi.toml")) ? readFileSync(join(user, "yazi.toml"), "utf8") : null;
  writeFileSync(join(dir, "yazi.toml"), treeYaziToml(userToml));
  if (!existsSync(join(dir, "keymap.toml"))) writeFileSync(join(dir, "keymap.toml"), TREE_KEYMAP);
  writeFileSync(join(dir, "helix-open"), OPENER_SCRIPT);
  chmodSync(join(dir, "helix-open"), 0o755);
  return { yazi, ya, version: null, configDir: dir, opener: join(dir, "helix-open"), userConfig: hasUser ? user : null };
}

/** `ya emit-to <clientId> <name> <args...>`: drive a running tree. */
export function yaEmit(ya: string, clientId: string, name: string, args: string[]): Promise<void> {
  return new Promise((resolve, reject) => {
    execFile(ya, ["emit-to", clientId, name, ...args], { timeout: 3000 }, (error) => (error ? reject(error) : resolve()));
  });
}
