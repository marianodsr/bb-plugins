// The file tree beside the editor is yazi, in its own bb terminal session.
// This prepares its configuration directory in the plugin's data: the user's
// own yazi configuration is linked in (keymap, theme, init.lua, plugins,
// flavors) and never written; yazi.toml is a copy of theirs with two settings
// added only when they have not set them: one column (the pane is narrow) and
// an `edit` opener that opens the file in the bound Helix and returns at once.
import { execFile } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { resolveExecutable } from "./doctor";

/** Opens the chosen files in the Helix serving this tree's thread (BB_THREAD_ID). */
export const OPEN_COMMAND = `"\${BB_CLI:-bb}" hx tree-open "$@"`;

const LINKED = ["keymap.toml", "theme.toml", "init.lua", "package.toml", "plugins", "flavors"];

export interface YaziSetup {
  yazi: string | null;
  ya: string | null;
  version: string | null;
  configDir: string | null;
  /** Where the user's own configuration was read from, if anywhere. */
  userConfig: string | null;
}

export function userConfigDir(env: NodeJS.ProcessEnv = process.env): string {
  return env.YAZI_CONFIG_HOME || join(env.XDG_CONFIG_HOME || join(homedir(), ".config"), "yazi");
}

/**
 * The tree's yazi.toml: the user's text with `ratio` and the `edit` opener
 * added when absent. Keys go right under an existing table header, or in a
 * new table at the end, so the result stays valid TOML.
 */
export function treeYaziToml(user: string | null): string {
  let text = user ?? "";
  const add = (table: string, key: string, line: string) => {
    const header = new RegExp(`^\\s*\\[${table}\\]\\s*$`, "mu");
    const section = (() => {
      const start = header.exec(text);
      if (!start) return null;
      const rest = text.slice(start.index + start[0].length);
      const next = /^\s*\[/mu.exec(rest);
      return rest.slice(0, next ? next.index : rest.length);
    })();
    if (section !== null && new RegExp(`^\\s*${key}\\s*=`, "mu").test(section)) return;
    const match = header.exec(text);
    if (match) text = `${text.slice(0, match.index + match[0].length)}\n${line}${text.slice(match.index + match[0].length)}`;
    else text = `${text.trimEnd()}${text.trim() ? "\n\n" : ""}[${table}]\n${line}\n`;
  };
  // yazi 0.4 calls the file browser `manager`.
  add("manager", "ratio", "ratio = [0, 1, 0]");
  add("opener", "edit", `edit = [{ run = '${OPEN_COMMAND}', desc = "Open in Helix", orphan = true, for = "unix" }]`);
  return `# Generated by Helix Bridge for the file tree beside the editor, from your\n# own yazi.toml (which is never written).\n${text}`;
}

export function prepareYazi(dataDir: string): YaziSetup {
  const yazi = resolveExecutable("yazi");
  const ya = resolveExecutable("ya");
  if (!yazi) return { yazi: null, ya, version: null, configDir: null, userConfig: null };
  const user = userConfigDir();
  const hasUser = existsSync(user);
  const dir = join(dataDir, "yazi-config");
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  if (hasUser) {
    for (const name of LINKED) {
      const from = join(user, name);
      if (existsSync(from)) symlinkSync(from, join(dir, name));
    }
  }
  const userToml = hasUser && existsSync(join(user, "yazi.toml")) ? readFileSync(join(user, "yazi.toml"), "utf8") : null;
  writeFileSync(join(dir, "yazi.toml"), treeYaziToml(userToml));
  return { yazi, ya, version: null, configDir: dir, userConfig: hasUser ? user : null };
}

/** `ya emit-to <clientId> <name> <args...>`: drive a running tree. */
export function yaEmit(ya: string, clientId: string, name: string, args: string[]): Promise<void> {
  return new Promise((resolve, reject) => {
    execFile(ya, ["emit-to", clientId, name, ...args], { timeout: 3000 }, (error) => (error ? reject(error) : resolve()));
  });
}
